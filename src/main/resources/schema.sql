    address VARCHAR2(300),
    job_title VARCHAR2(100),
    business_number VARCHAR2(20),
    company_name VARCHAR2(200),
    ceo_name VARCHAR2(50),
    workplace_address VARCHAR2(300),
    terms_service CHAR(1) DEFAULT 'N',
    terms_privacy CHAR(1) DEFAULT 'N',
    terms_marketing CHAR(1) DEFAULT 'N',
    terms_corporate CHAR(1) DEFAULT 'N',
    role VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    oauth_provider VARCHAR2(20) DEFAULT 'LOCAL' NOT NULL,
    oauth_id VARCHAR2(100),
    nickname VARCHAR2(100),
    profile_image VARCHAR2(1000),
    kakao_welcome_sent CHAR(1) DEFAULT 'N',
    kakao_welcome_sent_at TIMESTAMP,
    email_verified CHAR(1) DEFAULT 'N' NOT NULL,
    phone_verified CHAR(1) DEFAULT 'N' NOT NULL,
    verification_channel VARCHAR2(20) DEFAULT 'EMAIL',
    verification_code VARCHAR2(20),
    verification_expires TIMESTAMP,
    trust_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

