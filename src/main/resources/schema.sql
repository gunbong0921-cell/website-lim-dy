-- Hexaq DDL (참고용). 실행은 spring.jpa.hibernate.ddl-auto=update 가 담당한다.

CREATE TABLE HEXAQ_MEMBER (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR2(50) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    name VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    phone VARCHAR2(30) NOT NULL,
    company VARCHAR2(100),
    email_verified CHAR(1) DEFAULT 'N' NOT NULL,
    verification_code VARCHAR2(20),
    verification_expires TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE HEXAQ_FREE_BOARD (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    content CLOB NOT NULL,
    writer VARCHAR2(50) NOT NULL,
    password VARCHAR2(255) NOT NULL,
    visit_count NUMBER DEFAULT 0 NOT NULL,
    like_count NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE HEXAQ_QNA_BOARD (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    content CLOB NOT NULL,
    writer VARCHAR2(50) NOT NULL,
    solution VARCHAR2(20) DEFAULT 'general' NOT NULL,
    visit_count NUMBER DEFAULT 0 NOT NULL,
    like_count NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

-- 기존 테이블에 solution 컬럼이 없을 때만 성공한다 (continue-on-error=true).
ALTER TABLE HEXAQ_QNA_BOARD ADD solution VARCHAR2(20) DEFAULT 'general' NOT NULL;
CREATE INDEX IDX_HEXAQ_QNA_SOLUTION ON HEXAQ_QNA_BOARD (solution, id);

CREATE TABLE HEXAQ_ARCHIVE_BOARD (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    content CLOB NOT NULL,
    writer VARCHAR2(50) NOT NULL,
    visit_count NUMBER DEFAULT 0 NOT NULL,
    like_count NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE HEXAQ_BOARD_FILE (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id NUMBER NOT NULL,
    original_name VARCHAR2(255) NOT NULL,
    stored_name VARCHAR2(255) NOT NULL,
    content_type VARCHAR2(100),
    file_size NUMBER,
    file_type VARCHAR2(20) NOT NULL
);

CREATE TABLE HEXAQ_COMMENT (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id NUMBER NOT NULL,
    writer VARCHAR2(50) NOT NULL,
    content VARCHAR2(2000) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE HEXAQ_BOARD_LIKE (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_type VARCHAR2(20) NOT NULL,
    board_id NUMBER NOT NULL,
    member_login_id VARCHAR2(50) NOT NULL,
    CONSTRAINT uk_board_like UNIQUE (board_type, board_id, member_login_id)
);
